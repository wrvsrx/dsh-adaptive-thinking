import { readFileSync, writeFileSync } from 'node:fs';
const read = name => readFileSync(new URL(name, import.meta.url), 'utf8');
const operations = read('operations.js').replace(/\nexport \{ NS, readRoute, planEdit \};\s*$/, '');
const client = read('client.entry.js');
const built = `// Generated by npm run build; edit client.entry.js and operations.js instead.\nwindow.__ModuleLoader__.load({ id: 'dsh-adaptive-thinking-local', factory(require) {\n${operations}\n${client}\n} });\n`;
if (process.argv.includes('--check')) {
  if (read('client.js') !== built) throw new Error('Generated client.js is out of date.');
} else writeFileSync(new URL('client.js', import.meta.url), built);
